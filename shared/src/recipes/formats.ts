import { shellQuote } from '../shell.js';
import { exportRecipe, injectVars, paramVar, recipeStepInfo, type ExportInput } from './export.js';
import { findPlaceholders, substitute, type RecipeParam } from './params.js';

/** Other ways to hand a recipe to someone: an image recipe, a compose project, an Ansible playbook. */
export type ExportFormat = 'bash' | 'dockerfile' | 'compose' | 'ansible';
export const EXPORT_FORMATS: { id: ExportFormat; label: string }[] = [
  { id: 'bash', label: 'Bash script' },
  { id: 'dockerfile', label: 'Dockerfile' },
  { id: 'compose', label: 'Docker Compose' },
  { id: 'ansible', label: 'Ansible playbook' },
];

export interface ExportFile {
  name: string;
  content: string;
}
export interface ExportResult {
  files: ExportFile[];
  /** Things the person should know: steps that were left out or approximated. */
  notes: string[];
}

const oneLine = (s: string) => s.replace(/[\r\n]+/g, ' ');
const wrapComment = (text: string, width = 90): string[] => {
  const out: string[] = [];
  let cur = '';
  for (const w of text.split(/\s+/)) {
    if (cur && cur.length + w.length + 1 > width) {
      out.push(cur);
      cur = w;
    } else cur = cur ? `${cur} ${w}` : w;
  }
  if (cur) out.push(cur);
  return out.map((l) => `# ${l}`);
};

/** Parameters used by the steps or declared by the recipe, with their declaration (if any). */
function allParams(input: ExportInput): { name: string; p?: RecipeParam }[] {
  const used = new Set<string>();
  input.steps.forEach((s) => findPlaceholders(s.params, used));
  const names = [...new Set([...(input.params ?? []).map((p) => p.name), ...used])];
  return names.map((name) => ({ name, p: input.params?.find((x) => x.name === name) }));
}

/** Sentinel substitution (see export.ts) so steps built from placeholders still validate. */
function stepInfos(input: ExportInput, target: 'script' | 'image' = 'script') {
  const used = new Set<string>();
  input.steps.forEach((s) => findPlaceholders(s.params, used));
  const sentinels = Object.fromEntries(
    [...used].map((n) => [n, `__GFVPARAM_${n.toUpperCase()}__`]),
  );
  return input.steps.map((s) => {
    const info = recipeStepInfo(s.actionId, substitute(s.params, sentinels), target);
    return { ...s, info: info && { ...info, commands: info.commands.map(injectVars) } };
  });
}

// --- Dockerfile ------------------------------------------------------------------------------------

/** Things that only make sense on a running machine, not while building an image. */
const NOT_FOR_IMAGES = /(^|[\s;&|(])(systemctl|service|ufw|journalctl|docker|reboot|shutdown)\b/;

export function exportDockerfile(input: ExportInput): ExportResult {
  const notes: string[] = [];
  const params = allParams(input);
  const lines: string[] = [
    '# syntax=docker/dockerfile:1',
    `# Recipe: ${oneLine(input.name)}`,
    `# Generated by GFV on ${input.generatedAt.toISOString().slice(0, 10)}. Build:  docker build -t my-image .`,
    'FROM ubuntu:24.04',
    'ENV DEBIAN_FRONTEND=noninteractive',
    '',
  ];
  if (params.length) {
    lines.push('# Parameters: override with  --build-arg NAME=value');
    for (const { name, p } of params) {
      const v = paramVar(name);
      if (p?.secret) {
        lines.push(
          `# ${v} is a SECRET in the recipe. Build arguments are stored in the image history: prefer a`,
          '# BuildKit secret mount for real passwords. It must still be provided:',
          `ARG ${v}`,
        );
      } else if (p?.default !== undefined)
        lines.push(`ARG ${v}=${JSON.stringify(p.default)}  # ${oneLine(p.label)}`);
      else lines.push(`ARG ${v}`);
      if (p?.secret || p?.default === undefined)
        lines.push(
          `RUN test -n "$${'{'}${v}}" || { echo ${shellQuote(`Set --build-arg ${v}`)} >&2; exit 1; }`,
        );
    }
    lines.push('');
  }

  const infos = stepInfos(input, 'image');
  infos.forEach(({ actionId, info }, i) => {
    const head = `# Step ${i + 1}/${infos.length}: ${info?.title ?? actionId}`;
    if (!info) {
      lines.push(
        head,
        `# Skipped: "${oneLine(actionId)}" is not available in this version of GFV.`,
        '',
      );
      notes.push(
        `Step ${i + 1} (${actionId}) is not available in this version of GFV and was left out.`,
      );
      return;
    }
    // A Docker build runs as root, so sudo is dropped.
    const cmds = info.commands.map((c) => c.replace(/\$SUDO /g, ''));
    if (cmds.some((c) => NOT_FOR_IMAGES.test(c))) {
      lines.push(
        head,
        ...wrapComment(
          `Skipped: "${info.title}" starts or manages something on a running machine, which does not apply while building an image.`,
        ),
        '',
      );
      notes.push(
        `Step ${i + 1} (${info.title}) does not apply to an image build and was left out.`,
      );
      return;
    }
    lines.push(head, ...wrapComment(info.explain), ...cmds.map((c) => `RUN ${c}`), '');
  });
  if (infos.length === 0) lines.push('# (This recipe has no steps.)', '');
  return { files: [{ name: 'Dockerfile', content: lines.join('\n') }], notes };
}

// --- Docker Compose ----------------------------------------------------------------------------------

export function exportCompose(input: ExportInput): ExportResult {
  const docker = exportDockerfile(input);
  const params = allParams(input);
  const lines: string[] = [
    `# Recipe: ${oneLine(input.name)}`,
    `# Generated by GFV on ${input.generatedAt.toISOString().slice(0, 10)}. Put this next to the Dockerfile and run:  docker compose up --build`,
    'services:',
    '  app:',
    '    build:',
    '      context: .',
  ];
  if (params.length) {
    lines.push('      args:');
    for (const { name, p } of params) {
      const v = paramVar(name);
      lines.push(
        `        ${v}: ${JSON.stringify(p?.secret || p?.default === undefined ? `\${${v}:?set ${v}}` : `\${${v}:-${p.default}}`)}`,
      );
    }
  }
  lines.push(
    '    restart: unless-stopped',
    '    # The recipe prepares the image; give it the command your application needs, for example:',
    '    # command: ["node", "server.js"]',
    '    tty: true',
    '',
  );
  return {
    files: [{ name: 'docker-compose.yml', content: lines.join('\n') }, ...docker.files],
    notes: [
      ...docker.notes,
      'The compose file only builds the image: add your own command or ports for your application.',
    ],
  };
}

// --- Ansible ----------------------------------------------------------------------------------------

/** A YAML double-quoted scalar (JSON strings are valid YAML). Placeholders {{x}} become Jinja {{ x }}. */
const y = (s: string) => JSON.stringify(s.replace(/\{\{\s*([a-z][a-z0-9_]*)\s*\}\}/g, '{{ $1 }}'));

interface Task {
  name: string;
  /** The module call, already as YAML lines (indented by the caller). */
  body: string[];
  comment?: string[];
}

function moduleTask(actionId: string, params: Record<string, unknown>): string[] | null {
  const str = (k: string) => (typeof params[k] === 'string' ? (params[k] as string) : undefined);
  switch (actionId) {
    case 'files.mkdir':
      return ['ansible.builtin.file:', `  path: ${y(str('path') ?? '')}`, '  state: directory'];
    case 'files.delete-path':
      return ['ansible.builtin.file:', `  path: ${y(str('path') ?? '')}`, '  state: absent'];
    case 'files.chmod': {
      const mode = str('mode')?.padStart(4, '0');
      return [
        'ansible.builtin.file:',
        `  path: ${y(str('path') ?? '')}`,
        `  mode: ${y(mode ?? '0644')}`,
        ...(params.recursive ? ['  recurse: true'] : []),
      ];
    }
    default: {
      const m = /^service\.(start|stop|restart|enable|disable)$/.exec(actionId);
      if (!m) return null;
      const verb = m[1]!;
      return [
        'ansible.builtin.systemd:',
        `  name: ${y(str('unit') ?? '')}`,
        ...(verb === 'enable'
          ? ['  enabled: true']
          : verb === 'disable'
            ? ['  enabled: false']
            : [
                `  state: ${verb === 'start' ? 'started' : verb === 'stop' ? 'stopped' : 'restarted'}`,
              ]),
      ];
    }
  }
}

export function exportAnsible(input: ExportInput): ExportResult {
  const notes: string[] = [];
  const params = allParams(input);
  const envLines = params.length
    ? [
        '      environment:',
        ...params.map(
          ({ name }) => `        ${paramVar(name)}: ${JSON.stringify(`{{ ${name} }}`)}`,
        ),
      ]
    : [];

  const infos = stepInfos(input);
  const tasks: Task[] = infos.map(({ actionId, params: raw, info }, i) => {
    const title = `Step ${i + 1}/${infos.length}: ${info?.title ?? actionId}`;
    if (!info) {
      notes.push(
        `Step ${i + 1} (${actionId}) is not available in this version of GFV and was left out.`,
      );
      return {
        name: title,
        body: [
          'ansible.builtin.debug:',
          `  msg: ${y(`Skipped: ${actionId} is not available in this version of GFV.`)}`,
        ],
      };
    }
    // `info` exists, so the step validated (with sentinels standing in for parameters). The module call is
    // built from the raw params: strings keep their {{placeholders}}, which become Jinja variables.
    const mod = moduleTask(actionId, (raw ?? {}) as Record<string, unknown>);
    if (mod) return { name: title, body: mod, comment: wrapComment(info.explain) };
    // No clean module: run the same commands in a shell. Parameter values reach the shell as environment
    // variables (never pasted into the command text), exactly like the bash export.
    notes.push(
      `Step ${i + 1} (${info.title}) runs as a shell task: there is no matching Ansible module.`,
    );
    const cmds = info.commands.map((c) => c.replace(/\$SUDO /g, ''));
    return {
      name: title,
      comment: wrapComment(info.explain),
      body: [
        'ansible.builtin.shell: |',
        ...cmds.flatMap((c) => c.split('\n')).map((c) => `  ${c}`),
        'args:',
        '  executable: /bin/bash',
      ],
    };
  });

  const lines: string[] = [
    '---',
    `# Recipe: ${oneLine(input.name)}`,
    `# Generated by GFV on ${input.generatedAt.toISOString().slice(0, 10)}. Run:  ansible-playbook -i inventory recipe.yml`,
    `- name: ${y(oneLine(input.name))}`,
    '  hosts: all',
    '  become: true',
  ];
  const defaults = params.filter(({ p }) => !p?.secret && p?.default !== undefined);
  const asked = params.filter(({ p }) => p?.secret || p?.default === undefined);
  if (defaults.length) {
    lines.push(
      '  vars:',
      ...defaults.map(
        ({ name, p }) => `    ${name}: ${JSON.stringify(p!.default)}  # ${oneLine(p!.label)}`,
      ),
    );
  }
  if (asked.length) {
    lines.push(
      '  vars_prompt:',
      ...asked.flatMap(({ name, p }) => [
        `    - name: ${name}`,
        `      prompt: ${JSON.stringify(oneLine(p?.label ?? name))}`,
        `      private: ${p?.secret ? 'true' : 'false'}`,
      ]),
    );
  }
  lines.push('  tasks:');
  for (const t of tasks) {
    for (const c of t.comment ?? []) lines.push(`    ${c}`);
    lines.push(`    - name: ${y(t.name)}`);
    // Module body goes under the task; `args:` and `environment:` are siblings of the module.
    const split = t.body.indexOf('args:');
    const main = split === -1 ? t.body : t.body.slice(0, split);
    const rest = split === -1 ? [] : t.body.slice(split);
    lines.push(...main.map((l) => `      ${l}`), ...rest.map((l) => `      ${l}`));
    if (envLines.length && t.body[0]?.startsWith('ansible.builtin.shell')) lines.push(...envLines);
    lines.push('');
  }
  if (tasks.length === 0) lines.push('    []', '');
  return { files: [{ name: 'recipe.yml', content: lines.join('\n') }], notes };
}

export function exportAs(format: ExportFormat, input: ExportInput): ExportResult {
  switch (format) {
    case 'dockerfile':
      return exportDockerfile(input);
    case 'compose':
      return exportCompose(input);
    case 'ansible':
      return exportAnsible(input);
    default:
      return { files: [{ name: 'recipe.sh', content: exportRecipe(input) }], notes: [] };
  }
}
